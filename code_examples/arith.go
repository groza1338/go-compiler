package main

import "fmt"

func main() {
    var a int = 10
    var b int = 3
    fmt.Print(a + b)
    fmt.Print(" ")
    fmt.Print(a - b)
    fmt.Print(" ")
    fmt.Print(a * b)
    fmt.Print(" ")
    fmt.Print(a / b)
    fmt.Print(" ")
    fmt.Print(a % b)
    fmt.Print(" ")

    var x float64 = 2.5
    var y float64 = 1.5
    fmt.Print(x + y)
    fmt.Print(" ")
    fmt.Print(x - y)
    fmt.Print(" ")
    fmt.Print(x * y)
    fmt.Print(" ")
    fmt.Print(x / y)
    fmt.Print(" ")
    fmt.Print(x + 2)
}
